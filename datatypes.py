#Primitive common
#int
a = 10
print(a)
a = -5
print(a, type(a))

#float - decimal price, height, weight
height = 165.5
print(height, type(height))

#String
gender = 'f'
print(gender, type(gender))
name = "MD AFFAN ANWAR"
